#!/usr/bin/env python3
"""Original nine-slice Plasma SVGs and QML from the shared V4 token contract."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
HERE=Path(__file__).resolve().parent
TOKENS=HERE.parent/'identity-v4/TOKENS.json'
T=json.loads(TOKENS.read_text()); C=T['color'];G=T['geometry']
THEME=HERE/'theme'

def rect(id,x,y,w,h,fill,extra=''):
    return f'<rect id="{id}" x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" {extra}/>'

def frame(prefix,x,y,fill,stroke='none',indicator=None,opacity=1):
    """Independent original paths, no clipping/bounding-box trick or copied artwork."""
    p=(prefix+'-') if prefix else ''; out=[]
    # 40-square frame, 6-square corners; each ID has only its own geometry.
    for side,xx,yy,w,h in [('center',6,6,28,28),('top',6,0,28,6),('bottom',6,34,28,6),('left',0,6,6,28),('right',34,6,6,28)]:
        g=rect(p+side,x+xx,y+yy,w,h,fill,f'fill-opacity="{opacity}"')
        if stroke!='none' and side in ('top','bottom','left','right'):
            if side in ('top','bottom'):
                border=f'<rect x="{x+6}" y="{y+(0 if side=="top" else 39)}" width="28" height="1" fill="{stroke}"/>'
            else:
                border=f'<rect x="{x+(0 if side=="left" else 39)}" y="{y+6}" width="1" height="28" fill="{stroke}"/>'
            # Filled bands stay inside their slice. SVG stroke bounds otherwise
            # expand 28px groups to 29px and create tiled alpha seams in KSvg.
            g=f'<g id="{p+side}">'+g.replace('id="'+p+side+'"','')+border+'</g>'
        if indicator and side=='bottom':
            g=f'<g id="{p+side}">'+g.replace('id="'+p+side+'"','')+f'<path d="M{x+12},{y+37}h16" stroke="{indicator}" stroke-width="2" stroke-linecap="round"/></g>'
        out.append(g)
    corners={
      'topleft':('M6,0H6V6H0A6,6 0 0 1 6,0Z','M6,1V6H1A5,5 0 0 1 6,1Z'),
      'topright':('M34,0A6,6 0 0 1 40,6H34Z','M34,1A5,5 0 0 1 39,6H34Z'),
      'bottomleft':('M0,34H6V40A6,6 0 0 1 0,34Z','M1,34H6V39A5,5 0 0 1 1,34Z'),
      'bottomright':('M34,34H40A6,6 0 0 1 34,40Z','M34,34H39A5,5 0 0 1 34,39Z')}
    for name,(d,inner) in corners.items():
        out.append(f'<g id="{p+name}" transform="translate({x},{y})"><path d="{d}" fill="{fill}" fill-opacity="{opacity}"/>'+ (f'<path d="{d} {inner}" fill="{stroke}" fill-rule="evenodd"/>' if stroke!='none' else '')+'</g>')
    return ''.join(out)

def hints(prefix,x,y,top=4,bottom=4,left=4,right=4):
    p=(prefix+'-') if prefix else ''
    return ''.join(rect(p+'hint-'+side+'-margin',x+i*14,y,w,h,'#ff00ff') for i,(side,w,h) in enumerate([('top',2,top),('bottom',2,bottom),('left',left,2),('right',right,2)]))

def svg(body,w=560,h=360):
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- SPDX-License-Identifier: MIT; original Steins OS geometry, generated from TOKENS.json. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{body}</svg>\n'''

def write():
    qml='// Generated by generate.py from identity-v4/TOKENS.json; SPDX-License-Identifier: MIT\nimport QtQuick\nQtObject {\n'
    props={'canvas':C['canvas'],'raised':C['raised'],'raisedHover':C['raisedHover'],'input':C['input'],'border':C['border'],'text':C['text'],'muted':C['muted'],'subtle':C['subtle'],'selection':C['selection'],'brandAccent':C['accent'],'warning':C['warning'],'error':C['error']}
    qml+=''.join(f'    readonly property color {k}: "{v}"\n' for k,v in props.items())
    ints={'panelHeight':G['panelHeight'],'meterWidth':G['compactMeterPreferredWidth'],'meterMinimumWidth':G['compactMeterMinimumWidth'],'meterHeight':G['compactMeterHeight'],'controlTarget':G['controlTarget'],'controlRadius':T['radius']['control'],'borderWidth':T['stroke']['border'],'focusWidth':T['stroke']['focus'],'digitSize':T['typography']['sizes']['panelDigits']}
    qml+=''.join(f'    readonly property int {k}: {v}\n' for k,v in ints.items())
    qml+=f'    readonly property string uiFamily: "{T["typography"]["uiFamily"]}"\n    readonly property string monoFamily: "{T["typography"]["terminalFamily"]}"\n}}\n'
    (HERE/'package/contents/ui/DesignTokens.qml').write_text(qml)
    for prefix,opacity in [('',T['opacity']['panel']),('opaque/',1),('translucent/',T['opacity']['panel'])]:
        folder=THEME/prefix/'widgets';folder.mkdir(parents=True,exist_ok=True)
        content=frame('',0,0,C['panel'],C['border'],opacity=opacity)+hints('',0,60,top=4,bottom=4,left=6,right=6)
        # No separate floating shadow: the anchored panel has a simple readable edge.
        content+=rect('hint-tile-center',0,85,1,1,'#ff00ff')
        content+=rect('hint-stretch-borders',12,85,1,1,'#ff00ff')
        content+=''.join(rect('hint-'+s+'-inset',i*12,95,0.001 if s in ('left','right') else 2,2 if s in ('left','right') else 0.001,'#00ff00') for i,s in enumerate(['top','bottom','left','right']))
        (folder/'panel-background.svg').write_text(svg(content,100,110))
        # Popup bodies must separate their text from windows/wallpaper below.
        # Override every transparency variant so Breeze cannot supply a translucent
        # dialog behind an otherwise opaque Steins Lab calendar/tray/menu.
        for relative,margin in [('dialogs/background.svg',4),('widgets/background.svg',14)]:
            target=THEME/prefix/relative;target.parent.mkdir(parents=True,exist_ok=True)
            popup=frame('',0,0,C['raised'],C['border'],opacity=1)
            popup+=frame('mask',60,0,'#ffffff',opacity=1)
            popup+=hints('',0,60,top=margin,bottom=margin,left=margin,right=margin)
            popup+=rect('hint-tile-center',0,85,1,1,'#ff00ff')
            popup+=rect('hint-stretch-borders',12,85,1,1,'#ff00ff')
            popup+=''.join(rect('hint-'+s+'-inset',i*12,95,0.001 if s in ('left','right') else 2,2 if s in ('left','right') else 0.001,'#00ff00') for i,s in enumerate(['top','bottom','left','right']))
            target.write_text(svg(popup,120,110))
    body=''
    for n,(state,fill,border,ink) in enumerate([
       ('normal',C['panel'],'none',C['subtle']),('hover',C['raisedHover'],'none',C['muted']),
       ('focus',C['selection'],C['border'],C['accent']),('attention',C['raised'],C['warning'],C['warning']),
       ('minimized',C['panel'],'none',C['subtle']),('progress',C['selection'],'none',C['accent'])]):
        for d,orient in enumerate(['','north-','west-','east-']):
            name=orient+state;x=d*100;y=n*70
            body+=frame(name,x,y,fill,border,indicator=ink)
            body+=hints(name,x,y+45,top=6,bottom=6,left=3,right=3)
    # Native task grouping chevron remains a familiar three-dot cue.
    for d,side in enumerate(['bottom','left','top','right']):
        x=410;y=15+d*25
        body+=f'<g id="group-expander-{side}">'+''.join(f'<circle cx="{x+i*4}" cy="{y}" r="1" fill="{C["muted"]}"/>' for i in range(3))+'</g>'
    body+=rect('hint-stretch-borders',440,220,1,1,'#ff00ff')
    (THEME/'widgets/tasks.svg').write_text(svg(body,470,430))
    body=''
    for n,(name,fill,stroke) in enumerate([('normal',C['selection'],'none'),('hover',C['raisedHover'],'none'),('pressed',C['selection'],C['accent']),('section',C['panel'],'none')]):
        body+=frame(name,n*100,0,fill,stroke)+hints(name,n*100,50,top=6,bottom=6,left=8,right=8)
    body+=rect('separator',0,80,40,1,C['border'])
    body+=rect('hint-stretch-borders',60,80,1,1,'#ff00ff')
    (THEME/'widgets/listitem.svg').write_text(svg(body,460,90))
    (THEME/'metadata.json').write_text(json.dumps({'KPlugin':{'Id':'SteinsLab','Name':'Steins Lab','Description':'Quiet graphite surfaces and original native panel/task frames for Steins OS','Version':'0.4.0','License':'MIT','Authors':[{'Name':'Steins OS contributors'}]},'X-Plasma-API':'5.0'},indent=2)+'\n')
    (THEME/'plasmarc').write_text('[Settings]\nFallbackTheme=default\n\n[ContrastEffect]\nenabled=false\n\n[BlurBehindEffect]\nenabled=false\n\n[AdaptiveTransparency]\nenabled=false\n')
    # Deliberate static palette: Plasma SVG recoloring cannot turn the whole panel into a world accent.
    colors=''
    def rgb(c):return ','.join(str(int(c[i:i+2],16)) for i in (1,3,5))
    for group,bg in [('Window','panel'),('View','input'),('Button','raised'),('Tooltip','raised'),('Complementary','panel')]:
        colors+=f'[Colors:{group}]\nBackgroundNormal={rgb(C[bg])}\nBackgroundAlternate={rgb(C["selection"])}\nForegroundNormal={rgb(C["text"])}\nForegroundInactive={rgb(C["muted"])}\nDecorationFocus={rgb(C["accent"])}\nDecorationHover={rgb(C["border"])}\nForegroundLink={rgb(C["accent"])}\nForegroundNegative={rgb(C["error"])}\nForegroundNeutral={rgb(C["warning"])}\nForegroundPositive={rgb(C["success"])}\n\n'
    colors+=f'[Colors:Selection]\nBackgroundNormal={rgb(C["selection"])}\nForegroundNormal={rgb(C["text"])}\n\n[General]\nColorScheme=SteinsLab\nName=Steins Lab\n\n[KDE]\ncontrast=5\n'
    (THEME/'colors').write_text(colors)
    for p in THEME.rglob('*.svg'):ET.parse(p)
    print('Generated QML token adapter and original SteinsLab Plasma theme')
if __name__=='__main__':write()
