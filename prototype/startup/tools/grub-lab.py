#!/usr/bin/env python3
"""Explicit GRUB background opt-in for the named disposable V3 guest only."""
import argparse
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import tempfile
import uuid

GUEST='SteinsOS-V3-Integration'
SIZES=('1280x800','1366x768')

def sha(data): return hashlib.sha256(data).hexdigest()

def regular(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError('Expected a regular, non-symlink file: '+str(path))
    info=path.stat()
    if info.st_uid!=os.geteuid() or info.st_mode & 0o022:
        raise ValueError('File ownership/permissions are unsafe: '+str(path))
    return path

def atomic(path,data,mode=0o644):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd,name=tempfile.mkstemp(prefix='.'+path.name+'-',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as stream: stream.write(data)
        os.chmod(name,mode);os.replace(name,path)
    finally:
        if os.path.exists(name):os.unlink(name)

class GuestGrub:
    """Fixed relative paths; root injection exists only for temporary-file tests."""
    def __init__(self,root=Path('/'),runner=None):
        self.root=Path(root)
        self.cfg=self.root/'etc/default/grub.d/steins-lab.cfg'
        self.compiled=self.root/'boot/grub/grub.cfg'
        self.store=self.root/'var/lib/steins-startup-prototype/grub-backups'
        self.state=self.store/'current.json'
        self.runner=runner or (lambda:subprocess.run(['/usr/sbin/update-grub'],check=True))

    def safe_paths(self):
        for path in (self.cfg.parent,self.compiled.parent,self.store):
            for parent in [path,*path.parents]:
                if parent==self.root.parent:break
                if parent.is_symlink():raise ValueError('Refusing symlink directory: '+str(parent))

    def restore(self,folder,metadata):
        if metadata['previous_exists']:
            data=regular(folder/'previous.cfg').read_bytes()
            if sha(data)!=metadata['previous_sha256']:raise ValueError('Backup configuration hash mismatch')
            atomic(self.cfg,data,metadata['previous_mode'])
        elif self.cfg.exists():
            regular(self.cfg).unlink()

    def apply(self,size):
        if size not in SIZES:raise ValueError('Unsupported resolution')
        self.safe_paths()
        if self.state.exists() or self.state.is_symlink():raise ValueError('A GRUB opt-in is active; roll it back before applying again')
        asset=self.root/f'usr/share/steins/startup/grub-background-{size}.png'
        if not regular(asset).read_bytes().startswith(b'\x89PNG\r\n\x1a\n'):raise ValueError('Invalid PNG background')
        previous=regular(self.cfg).read_bytes() if self.cfg.exists() or self.cfg.is_symlink() else None
        compiled=regular(self.compiled).read_bytes()
        text=('# Steins;OS V3 disposable guest opt-in; generated by grub-lab.py.\n'
              '# Stock gfxterm font/menu colors, timeout and kernel arguments are preserved.\n'
              'GRUB_TERMINAL_OUTPUT="gfxterm"\nGRUB_THEME=""\n'
              f'GRUB_BACKGROUND="/usr/share/steins/startup/grub-background-{size}.png"\n').encode()
        identity=dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+uuid.uuid4().hex[:8]
        folder=self.store/identity;folder.mkdir(parents=True,mode=0o700)
        metadata={'id':identity,'guest':GUEST,'resolution':size,'installed_sha256':sha(text),
                  'previous_exists':previous is not None,'previous_sha256':sha(previous) if previous is not None else None,
                  'previous_mode':stat.S_IMODE(self.cfg.stat().st_mode) if previous is not None else 0o644,
                  'compiled_sha256':sha(compiled),'compiled_mode':stat.S_IMODE(self.compiled.stat().st_mode)}
        if previous is not None:atomic(folder/'previous.cfg',previous,0o600)
        atomic(folder/'previous.grub.cfg',compiled,0o600)
        atomic(folder/'backup.json',(json.dumps(metadata,indent=2)+'\n').encode(),0o600)
        atomic(self.cfg,text)
        try:self.runner()
        except Exception:
            self.restore(folder,metadata)
            atomic(self.compiled,compiled,metadata['compiled_mode'])
            raise RuntimeError('update-grub failed; own config and prior generated grub.cfg restored; backup '+identity)
        atomic(self.state,(json.dumps(metadata,indent=2)+'\n').encode(),0o600)
        return metadata

    def rollback(self):
        self.safe_paths()
        metadata=json.loads(regular(self.state).read_text())
        identity=metadata['id']
        if not re.fullmatch(r'\d{8}T\d{6}Z-[a-f0-9]{8}',identity):raise ValueError('Invalid backup identity')
        folder=self.store/identity
        frozen=json.loads(regular(folder/'backup.json').read_text())
        if metadata!=frozen:raise ValueError('Backup metadata mismatch')
        if sha(regular(self.cfg).read_bytes())!=metadata['installed_sha256']:
            raise ValueError('steins-lab.cfg changed since apply; refusing to overwrite later edits')
        self.restore(folder,metadata)
        try:self.runner()
        except Exception:
            previous=regular(folder/'previous.grub.cfg').read_bytes()
            if sha(previous)!=metadata['compiled_sha256']:raise ValueError('Generated GRUB backup hash mismatch')
            atomic(self.compiled,previous,metadata['compiled_mode'])
            self.state.unlink()
            raise RuntimeError('Regeneration failed; prior generated grub.cfg restored from the verified backup')
        self.state.unlink()
        return {'rolled_back':identity,'previous_config_restored':metadata['previous_exists'],'backups_retained':True}

def guard():
    if os.geteuid()!=0:raise ValueError('This explicit guest-only operation requires root inside the disposable V3 VM')
    marker=Path('/run/steins-startup-v3-allow')
    if regular(marker).read_text().strip()!=GUEST:raise ValueError('Explicit V3 guest marker missing or incorrect')
    kind=subprocess.check_output(['/usr/bin/systemd-detect-virt','--vm'],text=True).strip()
    if kind not in ('qemu','kvm'):raise ValueError('This helper is restricted to the QEMU/KVM V3 test guest')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=['apply','rollback'])
    parser.add_argument('--resolution',choices=SIZES,default='1280x800')
    args=parser.parse_args();guard();lab=GuestGrub()
    result=lab.apply(args.resolution) if args.action=='apply' else lab.rollback()
    print(json.dumps(result,indent=2))
if __name__=='__main__':
    try:main()
    except Exception as error:raise SystemExit(str(error))
