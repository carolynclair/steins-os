#!/usr/bin/env python3
"""Regenerate only the original wallpaper and icon SVG artwork. (Worldline packs: generate_worldlines.py)"""
from pathlib import Path
import math
ROOT=Path(__file__).resolve().parents[1]
C=ROOT/'config'
O=C/'includes.chroot'
def write(path, text, executable=False):
    p=ROOT/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text)
    if executable:p.chmod(0o755)
def overlay(path,text,executable=False):write('config/includes.chroot/'+path,text,executable)
# Original vector artwork: no third-party imagery.
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_worldlines as worldlines
# The base wallpaper (greeter, installer welcome, first-login fallback) is the Steins Gate pack artwork,
# generated by the same code so the two can never drift apart. It has the title block top-left so the
# LightDM login box (left-centre) no longer covers it, and it carries no baked-in divergence number.
overlay('usr/share/backgrounds/steins/worldline.svg', worldlines.wallpaper(next(w for w in worldlines.WORLDLINES if w['id']=='steins-gate')))
for variant in ('oscilloscope','blueprint'):
    shapes=[]
    for x in range(0,1921,80):shapes.append(f'<path d="M{x} 0V1080"/>')
    for y in range(0,1081,80):shapes.append(f'<path d="M0 {y}H1920"/>')
    accent='#e99a45' if variant!='blueprint' else '#7da694'
    scene=''
    if variant=='oscilloscope':
        pts=' '.join(f'{x},{540-140*math.sin(x/72)*math.exp(-((x-1160)/470)**2)}' for x in range(630,1840,3))
        scene=f'<polyline points="{pts}" fill="none" stroke="{accent}" stroke-width="3"/>'
        scene+='<circle cx="1220" cy="540" r="270" fill="none" stroke="#7da694" stroke-opacity=".22"/>'
    else:
        for r in (150,210,300,370):scene+=f'<circle cx="1260" cy="530" r="{r}" fill="none" stroke="{accent}" stroke-opacity=".3"/>'
        scene+='<path d="M810 530h900M1260 80v900" stroke="#7da694" stroke-opacity=".4"/>'
    svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">
<defs><radialGradient id="g"><stop stop-color="#26302e"/><stop offset="1" stop-color="#11171b"/></radialGradient></defs>
<rect width="1920" height="1080" fill="url(#g)"/><g stroke="#8ea098" stroke-opacity=".045">{''.join(shapes)}</g>
{scene}<path d="M140 395h70" stroke="{accent}" stroke-width="4"/>
<text x="140" y="450" fill="#91a096" font-family="DejaVu Sans Mono" font-size="16" letter-spacing="4">FUTURE GADGET LABORATORY</text>
<text x="135" y="543" fill="#ece8dc" font-family="DejaVu Sans" font-size="76" font-weight="bold">Steins;OS</text>
<text x="140" y="588" fill="{accent}" font-family="DejaVu Sans Mono" font-size="18" letter-spacing="3">GATE OF STEINER / 001</text>
<text x="140" y="974" fill="#6e7f79" font-family="DejaVu Sans Mono" font-size="13" letter-spacing="2">EXPERIMENTAL SYSTEMS / OBSERVE · QUESTION · CREATE</text>
<path d="M140 935H1780" stroke="#8ea098" stroke-opacity=".2"/></svg>'''
    overlay(f'usr/share/backgrounds/steins/{variant}.svg',svg)
logo='''<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><rect width="128" height="128" rx="24" fill="#151b20"/><g fill="none" stroke="#e99a45" stroke-width="5"><path d="M30 30h68L30 98h68M48 30v20m32 28v20"/><circle cx="64" cy="64" r="50" stroke-width="2"/></g></svg>'''
overlay('usr/share/icons/hicolor/scalable/apps/steins-os.svg',logo)
print('Generated original wallpaper and icon artwork.')
